const translatableNodes = Array.from(document.querySelectorAll("[data-i18n]"));
const translatableTitleNodes = Array.from(document.querySelectorAll("[data-i18n-title]"));
const langButtons = Array.from(document.querySelectorAll(".lang-btn"));
const navLinks = Array.from(document.querySelectorAll(".section-nav a"));
const sectionIds = ["intro", "motivation", "experience", "strengths", "values", "closing"];

function applyLanguage(lang) {
    const selected = translations[lang] ? lang : "da";

    translatableNodes.forEach((node) => {
        const key = node.getAttribute("data-i18n");
        if (!key) {
            return;
        }
        const text = translations[selected][key];
        if (text) {
            node.textContent = text;
        }
    });

    translatableTitleNodes.forEach((node) => {
        const key = node.getAttribute("data-i18n-title");
        if (!key) {
            return;
        }
        const text = translations[selected][key];
        if (text) {
            node.setAttribute("title", text);
            node.setAttribute("aria-label", text);
        }
    });

    langButtons.forEach((button) => {
        const isActive = button.dataset.lang === selected;
        button.classList.toggle("active", isActive);
    });

    document.documentElement.lang = selected;
    window.localStorage.setItem("ferieraadgiver-language", selected);
}

langButtons.forEach((button) => {
    button.addEventListener("click", () => {
        const lang = button.dataset.lang || "da";
        applyLanguage(lang);
    });
});

const savedLanguage = window.localStorage.getItem("ferieraadgiver-language") || "da";
applyLanguage(savedLanguage);

const revealObserver = new IntersectionObserver(
    (entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add("visible");
            }
        });
    },
    {
        threshold: 0.12,
        rootMargin: "0px 0px -8% 0px"
    }
);

document.querySelectorAll(".reveal").forEach((section) => revealObserver.observe(section));

const navObserver = new IntersectionObserver(
    (entries) => {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) {
                return;
            }
            const id = entry.target.id;
            navLinks.forEach((link) => {
                const isActive = link.dataset.nav === id;
                link.classList.toggle("active", isActive);
            });
        });
    },
    {
        threshold: 0.5,
        rootMargin: "-20% 0px -35% 0px"
    }
);

sectionIds.forEach((id) => {
    const section = document.getElementById(id);
    if (section) {
        navObserver.observe(section);
    }
});
